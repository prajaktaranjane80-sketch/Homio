import Link from "next/link";

import type { PropertyRecord } from "./property.types";
import styles from "./PropertyNextStep.module.css";

type PropertyNextStepProps = Readonly<{
  property: PropertyRecord;
}>;

export default function PropertyNextStep({
  property,
}: PropertyNextStepProps) {
  const enquiryHref =
    "/enquiry?kind=property&id=" +
    encodeURIComponent(property.id) +
    "&mode=enquiry";

  const visitHref =
    "/enquiry?kind=property&id=" +
    encodeURIComponent(property.id) +
    "&mode=visit";

  return (
    <section
      className={styles.section}
      id="property-next-step"
      aria-labelledby="property-next-step-heading"
    >
      <div className={styles.content}>
        <span className={styles.eyebrow}>NEXT STEP PREVIEW</span>

        <h2 id="property-next-step-heading">
          Ready to take the conversation forward?
        </h2>

        <p className={styles.lead}>
          Prepare an enquiry draft or share your preferred visit details for
          this property. The connected submission and booking services are not
          available in this preview, so nothing will be sent or reserved.
        </p>

        <div className={styles.options}>
          <article
            id="property-next-step-enquiry"
            className={styles.option}
            aria-labelledby="property-enquiry-heading"
          >
            <span className={styles.optionLabel}>ENQUIRY</span>

            <h3 id="property-enquiry-heading">
              Ask about this property
            </h3>

            <p className={styles.optionDescription}>
              Add your question and preferred contact details. You can prepare
              the draft before leaving this page.
            </p>

            <Link
              href={enquiryHref}
              className={styles.primary}
              aria-describedby="property-enquiry-disclosure"
            >
              Prepare enquiry draft <span aria-hidden="true">↗</span>
            </Link>

            <p
              id="property-enquiry-disclosure"
              className={styles.disclosure}
            >
              Submission remains disabled until an authorized service is
              connected. No request has been created or sent; no lead, broker
              notification or reference number is generated by this preview.
            </p>
          </article>

          <article
            id="property-next-step-visit"
            className={styles.option}
            aria-labelledby="property-visit-heading"
          >
            <span className={styles.optionLabel}>VISIT</span>

            <h3 id="property-visit-heading">Plan a property visit</h3>

            <p className={styles.optionDescription}>
              Choose an in-person or video-walkthrough preference and a
              suitable time window.
            </p>

            <Link
              href={visitHref}
              className={styles.primary}
              aria-describedby="property-visit-disclosure"
            >
              Prepare visit request <span aria-hidden="true">↗</span>
            </Link>

            <p
              id="property-visit-disclosure"
              className={styles.disclosure}
            >
              Scheduling remains disabled until an authorized service is
              connected. No request has been created or sent, and this is not
              confirmed availability or a booking.
            </p>
          </article>
        </div>
      </div>
    </section>
  );
}
